"""Safe query execution against PostgreSQL.

Each query runs in its own transaction that is:

* opened ``READ ONLY`` (Postgres rejects any write with SQLSTATE 25006),
* bounded by ``SET LOCAL statement_timeout`` and ``lock_timeout``,
* always rolled back afterwards.

At most ``max_rows`` rows are fetched (one extra row is read to detect
truncation), so a missing LIMIT can never pull a whole table into memory.
"""

from __future__ import annotations

import logging
import time
from dataclasses import dataclass

import pandas as pd
import psycopg
from sqlalchemy.engine import Engine
from sqlalchemy.exc import DBAPIError, SQLAlchemyError

from .results import normalize_dataframe

logger = logging.getLogger(__name__)

# SQLSTATE codes we translate into friendlier messages
QUERY_CANCELED = "57014"
READ_ONLY_VIOLATION = "25006"
INSUFFICIENT_PRIVILEGE = "42501"
UNDEFINED_TABLE = "42P01"
UNDEFINED_COLUMN = "42703"

# Errors where asking the LLM to rewrite the query makes no sense.
NON_RETRYABLE_SQLSTATES = {READ_ONLY_VIOLATION, INSUFFICIENT_PRIVILEGE}


@dataclass
class QueryResult:
    sql: str
    df: pd.DataFrame
    row_count: int
    truncated: bool
    execution_ms: float

    @property
    def columns(self) -> list[str]:
        return list(self.df.columns)


class QueryExecutionError(Exception):
    def __init__(self, message: str, sqlstate: str | None = None, execution_ms: float = 0.0) -> None:
        super().__init__(message)
        self.message = message
        self.sqlstate = sqlstate
        self.execution_ms = execution_ms

    @property
    def is_timeout(self) -> bool:
        return self.sqlstate == QUERY_CANCELED

    @property
    def retryable(self) -> bool:
        return self.sqlstate not in NON_RETRYABLE_SQLSTATES


class QueryExecutor:
    def __init__(self, engine: Engine, timeout_seconds: int = 15, max_rows: int = 1000) -> None:
        self.engine = engine
        self.timeout_seconds = timeout_seconds
        self.max_rows = max_rows

    def execute(self, sql: str) -> QueryResult:
        timeout_ms = int(self.timeout_seconds * 1000)
        started = time.perf_counter()
        try:
            with self.engine.connect() as conn:
                trans = conn.begin()
                try:
                    conn.exec_driver_sql("SET TRANSACTION READ ONLY")
                    conn.exec_driver_sql(f"SET LOCAL statement_timeout = {timeout_ms}")
                    conn.exec_driver_sql("SET LOCAL lock_timeout = 3000")
                    # Use the raw DB-API cursor with no parameters, so the driver does not
                    # interpret '%' (e.g. in LIKE 'A%') as a placeholder. The SQL text has
                    # already been validated and regenerated by the safety layer.
                    cursor = conn.connection.dbapi_connection.cursor()
                    try:
                        cursor.execute(sql)
                        if cursor.description is None:
                            raise QueryExecutionError("The statement did not return rows.")
                        columns = [d[0] for d in cursor.description]
                        rows = cursor.fetchmany(self.max_rows + 1)
                    finally:
                        cursor.close()
                finally:
                    trans.rollback()
        except QueryExecutionError:
            raise
        except DBAPIError as exc:
            elapsed = (time.perf_counter() - started) * 1000
            raise self._translate(exc.orig, elapsed) from exc
        except psycopg.Error as exc:
            elapsed = (time.perf_counter() - started) * 1000
            raise self._translate(exc, elapsed) from exc
        except SQLAlchemyError as exc:
            elapsed = (time.perf_counter() - started) * 1000
            raise QueryExecutionError(f"Database error: {exc}", execution_ms=elapsed) from exc

        elapsed = (time.perf_counter() - started) * 1000
        truncated = len(rows) > self.max_rows
        rows = rows[: self.max_rows]
        df = normalize_dataframe(pd.DataFrame([tuple(r) for r in rows], columns=_dedupe_columns(columns)))
        return QueryResult(sql=sql, df=df, row_count=len(df), truncated=truncated, execution_ms=elapsed)

    def _translate(self, orig: Exception | None, elapsed_ms: float) -> QueryExecutionError:
        sqlstate = getattr(orig, "sqlstate", None) or getattr(orig, "pgcode", None)
        detail = str(orig).strip() if orig is not None else "Unknown database error"
        if sqlstate == QUERY_CANCELED:
            message = f"The query exceeded the {self.timeout_seconds}s time limit and was cancelled."
        elif sqlstate == READ_ONLY_VIOLATION:
            message = "The database rejected the statement because the connection is read-only."
        elif sqlstate == INSUFFICIENT_PRIVILEGE:
            message = f"Permission denied: {detail.splitlines()[0]}"
        else:
            message = detail
        logger.info("Query failed (%s): %s", sqlstate, detail.splitlines()[0] if detail else "")
        return QueryExecutionError(message, sqlstate=sqlstate, execution_ms=elapsed_ms)


def _dedupe_columns(columns: list[str]) -> list[str]:
    """Make column names unique (``SELECT a.id, b.id`` returns two 'id' columns)."""
    seen: dict[str, int] = {}
    out = []
    for col in columns:
        if col in seen:
            seen[col] += 1
            out.append(f"{col}_{seen[col]}")
        else:
            seen[col] = 0
            out.append(col)
    return out
